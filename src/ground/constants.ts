/**
 * 발판 상태 판정 임계값 — 시트 §02의 서술("적이 절반 이상 전진" / "후반 웨이브")을
 * 실제 수치로 확정한 곳. 매직넘버가 판정 코드에 흩어지지 않게 여기 한 곳에만 둔다.
 */

/**
 * 균열 임계 — **가장 전진한 적**의 전진율이 이 값 이상이면 발판이 갈라진다.
 *
 * ★ "적이 절반 이상 전진"을 **최대(가장 전진한 적)** 기준으로 읽는 이유 ★
 *   평균 전진율은 웨이브 중간에 새 적이 x≈1에 스폰될 때마다 **내려간다**. 즉 적 하나가
 *   사옥 코앞(x=0.05)에 붙어 있어도 갓 스폰된 적 다섯이 평균을 끌어내려 발판이 다시
 *   '정상'으로 되돌아간다 — 전황 표시가 위협을 **가리는** 셈이라 정보로서 실패한다.
 *   실제 위협은 언제나 가장 앞선 적이 만들고, 최대값 기준은 웨이브 안에서 단조적으로
 *   증가하므로 "위험이 다가온다"가 화면에서 되돌아가지 않는다.
 *
 * 0.5 = 전장의 절반. 시트 문구를 그대로 수치화했다. 경계는 **이상(>=)** 포함이다.
 */
export const CRACK_ADVANCE_THRESHOLD = 0.5;

/**
 * 후반 웨이브 임계 — `wave / waveCount`가 이 비율 이상이면 후반으로 본다.
 *
 * 0.7 = 마지막 30% 구간. R1(웨이브 5)에서는 4~5웨이브, 13웨이브 스테이지에서는
 * 10웨이브부터 함몰 단계가 열린다 — 보스(13웨이브) 전 구간이 확실히 포함된다.
 */
export const LATE_WAVE_PROGRESS = 0.7;
