/**
 * 청산 시 원금이 AUM으로 복귀하는 비율 (`trade.ts` `closePosition`).
 *
 * ★ 왜 승수(`GOLD_MULT`)가 아니라 환급률인가 ★
 * 한때 "골드 = 이익 × 3.0, 원금은 AUM으로 전액 복귀" 안을 검토했으나 **철회했다.**
 * 원금이 AUM으로 돌아오면 AUM이 **재순환**한다 — 세션 총 투입 S가 초기 AUM의 5~6배
 * (R1 기준 약 11,900)까지 불어나므로, 거기에 ×3 승수를 얹으면 골드가 폭발한다
 * (필요지출 2,700 대비 7,455). 승수는 "원금이 재순환하지 않는다"는 전제에서만 옳았다.
 *
 * 그래서 골드는 승수 없이 `max(pnl, 0)` 그대로 두고, 대신 왕복마다 원금의 30%를 태운다.
 * 총골드 = `STARTING_GOLD + 기본수입 + S × ρ` (ρ = 매매 수익률)이며, R1 게이트는
 * ρ=0.20 → 2,695 G(필요지출 2,700 아슬하게 통과) / ρ=0.15 → 2,100 G(실패)로 잡혔다.
 *
 * 이 값은 FR-8.1 잔여 AUM 계수(`AUM_SETTLEMENT_RATIO` = 0.15)와 한 쌍이다 —
 * **AUM은 의도적으로 나쁜 저장수단**이며, 쥐고 있으면 정산에서 15%밖에 못 건지고
 * 굴리면 왕복마다 30%가 탄다. 어느 쪽이든 "쌓아두기"가 답이 되지 않게 만든 구조다.
 */
export const REFUND_RATIO = 0.7;

/**
 * FR-8.1 정산에서 **잔여 AUM**을 자본금으로 환산할 때 쓰는 계수.
 *
 * v1.2의 0.5에서 내렸다. 청산이 원금을 AUM으로 되돌리는 구조에서는 잔여 AUM이 사실상
 * 항상 만액이라, 계수가 높으면 **"아무 매매도 안 하고 AUM을 쥐고만 있으면 전액 자본금"**
 * 이 되어 익스플로잇이 그쪽으로 이동한다. 0.15는 잔여 AUM을 "쓰지 않은 실탄에 대한
 * 소액 보상" 수준으로 눌러 그 경로를 죽인다.
 */
export const AUM_SETTLEMENT_RATIO = 0.15;

/**
 * FR-8.1 `aumGate` 임계치 — 잔여 AUM을 자본금으로 환산받기 위한 **이익 청산(`pnl > 0`) 최소 횟수**.
 *
 * v1.2는 이 조건이 "총 **진입** 횟수 ≥ 4"였다. 진입은 아무 판단 없이도 4회 채울 수 있어서,
 * 세탁 4회면 게이트가 열려 **방지책이 오히려 익스플로잇 체크리스트**가 됐다.
 * 조건을 "이익 청산 횟수"로 바꾸면 z≈0 왕복으로는 절대 충족할 수 없다 — 게이트를 열려면
 * 실제로 차트를 읽고 이익을 내야 한다.
 */
export const MIN_PROFIT_CLOSES_FOR_AUM_CREDIT = 4;

